  operation_id uuid not null,
  created_at timestamptz not null default now(),
  constraint t2_akt_correction_relation_check check (relation = 'supersedes'),
  constraint t2_akt_correction_pair_check check (original_akt_id <> replacement_akt_id),
  constraint t2_akt_correction_pair_unique unique (original_akt_id, replacement_akt_id),
  constraint t2_akt_correction_operation_unique unique (operation_id)
);

create index if not exists t2_akt_holat_tarix_akt_created_idx
  on public.t2_akt_holat_tarix (akt_id, created_at, id);
create unique index if not exists t2_akt_holat_tarix_operation_unique
