-- T2 F2 lifecycle / approval history (source-only until explicitly applied)
--
-- Compatibility rule: existing `t2_akt.holat` values remain the legacy
-- projection (`qoralama`, `tasdiqlangan`, `bekor`). The additive
-- `lifecycle_status` column is the canonical workflow state so existing
-- readers are not silently broken while new transitions become explicit.
-- `approved` rows are immutable. A correction creates a new draft row and a
-- link; it never mutates or deletes the approved source row.

begin;

alter table public.t2_akt
  add column if not exists lifecycle_status text,
  add column if not exists lifecycle_updated_at timestamptz,
  add column if not exists lifecycle_updated_by bigint,
  add column if not exists lifecycle_reason text,
  add column if not exists lifecycle_submitted_at timestamptz,
  add column if not exists lifecycle_checked_at timestamptz,
  add column if not exists lifecycle_approved_at timestamptz,
  add column if not exists lifecycle_rejected_at timestamptz,
  add column if not exists lifecycle_cancelled_at timestamptz,
  add column if not exists lifecycle_superseded_at timestamptz,
  add column if not exists correction_of_akt_id bigint;

-- Existing rows are mapped conservatively. No amount, quantity, date, or
-- approval value is invented; only the already persisted legacy status is
-- projected into the new workflow vocabulary.
update public.t2_akt
set lifecycle_status = case holat
  when 'tasdiqlangan' then 'approved'
  when 'bekor' then 'cancelled'
  else 'draft'
end
where lifecycle_status is null;

update public.t2_akt
set lifecycle_updated_at = coalesce(lifecycle_updated_at, yangilandi, yaratildi),
    lifecycle_approved_at = case when lifecycle_status = 'approved' then coalesce(lifecycle_approved_at, yangilandi, yaratildi) else lifecycle_approved_at end,
    lifecycle_cancelled_at = case when lifecycle_status = 'cancelled' then coalesce(lifecycle_cancelled_at, yangilandi, yaratildi) else lifecycle_cancelled_at end
where lifecycle_updated_at is null
   or lifecycle_status in ('approved', 'cancelled');

alter table public.t2_akt
  alter column lifecycle_status set default 'draft',
  alter column lifecycle_status set not null;

do $$
begin
  if not exists (select 1 from pg_constraint where conname = 't2_akt_lifecycle_status_check') then
    alter table public.t2_akt add constraint t2_akt_lifecycle_status_check
      check (lifecycle_status in ('draft','submitted','checked','approved','rejected','cancelled','superseded'));
  end if;
  if not exists (select 1 from pg_constraint where conname = 't2_akt_lifecycle_actor_fkey') then
    alter table public.t2_akt add constraint t2_akt_lifecycle_actor_fkey
      foreign key (lifecycle_updated_by) references public.t2_foydalanuvchi(id);
  end if;
  if not exists (select 1 from pg_constraint where conname = 't2_akt_correction_of_fkey') then
    alter table public.t2_akt add constraint t2_akt_correction_of_fkey
      foreign key (correction_of_akt_id) references public.t2_akt(id) on delete restrict;
  end if;
end $$;

create table if not exists public.t2_akt_holat_tarix (
  id bigint generated by default as identity primary key,
  kompaniya_id bigint not null references public.t2_kompaniya(id),
  akt_id bigint not null references public.t2_akt(id) on delete restrict,
  from_status text,
  to_status text not null,
  reason text,
  actor_id bigint references public.t2_foydalanuvchi(id),
  operation_id uuid,
  created_at timestamptz not null default now(),
  constraint t2_akt_holat_tarix_from_check check (from_status is null or from_status in ('draft','submitted','checked','approved','rejected','cancelled','superseded')),
  constraint t2_akt_holat_tarix_to_check check (to_status in ('draft','submitted','checked','approved','rejected','cancelled','superseded'))
);

create table if not exists public.t2_akt_correction_link (
  id bigint generated by default as identity primary key,
  kompaniya_id bigint not null references public.t2_kompaniya(id),
  original_akt_id bigint not null references public.t2_akt(id) on delete restrict,
  replacement_akt_id bigint not null references public.t2_akt(id) on delete restrict,
  relation text not null default 'supersedes',
  reason text,
